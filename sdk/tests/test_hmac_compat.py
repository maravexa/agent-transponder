def test_all_event_type_strings():
    mapping = {
        EventType.PROMPT: "prompt",
        EventType.RESPONSE: "response",
        EventType.TOOL_CALL: "tool_call",
        EventType.TOOL_RESULT: "tool_result",
        EventType.MEMORY_READ: "memory_read",
        EventType.MEMORY_WRITE: "memory_write",
        EventType.REASONING_STEP: "reasoning_step",
        EventType.ERROR: "error",
        EventType.RETRY: "retry",
        EventType.METADATA: "metadata",
    }
    for et, expected in mapping.items():
        e = _minimal_event()
        e.type = et
        data = json.loads(_canonical_json(e))
        assert data["type"] == expected, (
            f"{et!r}: expected {expected!r}, got {data['type']!r}"
        )


def test_all_severity_strings():
    mapping = {
        Severity.DEBUG: "debug",
        Severity.INFO: "info",
        Severity.WARNING: "warning",
        Severity.ERROR: "error",
        Severity.CRITICAL: "critical",
    }
    for sev, expected in mapping.items():
        e = _minimal_event()
        e.severity = sev
        data = json.loads(_canonical_json(e))
        assert data["severity"] == expected, (
            f"{sev!r}: expected {expected!r}, got {data['severity']!r}"
        )
